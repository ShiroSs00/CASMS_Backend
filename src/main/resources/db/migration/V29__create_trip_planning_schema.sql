-- Create sequence for Trip Business Codes (e.g. TR-1001)
CREATE SEQUENCE IF NOT EXISTS casms_trip_code_seq START WITH 1001 MAXVALUE 9999 NO CYCLE;

-- Add location_type to Port if not exists (nullable, no forced default backfill)
ALTER TABLE "Port" ADD COLUMN IF NOT EXISTS location_type VARCHAR(20);

-- Create Trip planning entities (Aligned to Upstream Planning Conceptual Model)
CREATE TABLE IF NOT EXISTS "Trip" (
    trip_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trip_code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    duration_days INT NOT NULL CHECK (duration_days > 0),
    duration_nights INT NOT NULL CHECK (duration_nights >= 0),
    trip_type VARCHAR(50) NOT NULL,
    planned_scope VARCHAR(50),
    ship_requirements TEXT,
    candidate_destinations TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    structural_locked_at TIMESTAMPTZ,
    revision BIGINT NOT NULL DEFAULT 1,
    created_by_user_id UUID REFERENCES "User"(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "TripScheduleVersion" (
    version_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trip_id UUID NOT NULL REFERENCES "Trip"(trip_id) ON DELETE CASCADE,
    version_number INT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    revision BIGINT NOT NULL DEFAULT 1,
    creator_id UUID REFERENCES "User"(user_id),
    submitter_id UUID REFERENCES "User"(user_id),
    submitted_revision BIGINT,
    content_hash VARCHAR(64),
    published_by UUID REFERENCES "User"(user_id),
    published_at TIMESTAMPTZ,
    rejection_reason VARCHAR(500),
    source_version_id UUID,
    time_policy_version VARCHAR(50),
    planning_policy_snapshot TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_trip_version UNIQUE (trip_id, version_number)
);

CREATE TABLE IF NOT EXISTS "TripPlanDay" (
    day_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    version_id UUID NOT NULL REFERENCES "TripScheduleVersion"(version_id) ON DELETE CASCADE,
    day_number INT NOT NULL,
    day_type VARCHAR(50),
    ship_time_zone_id VARCHAR(100) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    title VARCHAR(200),
    description TEXT,
    CONSTRAINT uq_version_day_number UNIQUE (version_id, day_number)
);

CREATE TABLE IF NOT EXISTS "TripPlanStop" (
    stop_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    version_id UUID NOT NULL REFERENCES "TripScheduleVersion"(version_id) ON DELETE CASCADE,
    client_key VARCHAR(100) NOT NULL,
    port_id UUID NOT NULL REFERENCES "Port"(port_id),
    destination_id UUID REFERENCES "Destination"(destination_id),
    stop_order INT NOT NULL,
    arrival_day_number INT NOT NULL,
    planned_arrival_time TIME,
    departure_day_number INT NOT NULL,
    planned_departure_time TIME,
    call_type VARCHAR(50) DEFAULT 'NORMAL',
    arrival_method VARCHAR(50) DEFAULT 'BERTH',
    all_aboard_day_number INT,
    all_aboard_time TIME,
    is_embarkation BOOLEAN NOT NULL DEFAULT FALSE,
    is_disembarkation BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_version_stop_client_key UNIQUE (version_id, client_key),
    CONSTRAINT uq_version_stop_order UNIQUE (version_id, stop_order)
);

CREATE TABLE IF NOT EXISTS "TripPlanEntry" (
    entry_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    version_id UUID NOT NULL REFERENCES "TripScheduleVersion"(version_id) ON DELETE CASCADE,
    day_id UUID NOT NULL REFERENCES "TripPlanDay"(day_id) ON DELETE CASCADE,
    client_key VARCHAR(100) NOT NULL,
    kind VARCHAR(50) NOT NULL,
    stop_id UUID REFERENCES "TripPlanStop"(stop_id) ON DELETE RESTRICT,
    service_id UUID,
    destination_id UUID REFERENCES "Destination"(destination_id),
    title VARCHAR(200) NOT NULL,
    start_day_number INT NOT NULL,
    planned_start_time TIME NOT NULL,
    end_day_number INT NOT NULL,
    planned_end_time TIME NOT NULL,
    time_zone_id VARCHAR(100),
    location_text VARCHAR(255),
    meeting_point VARCHAR(255),
    notes TEXT,
    CONSTRAINT uq_version_entry_client_key UNIQUE (version_id, client_key)
);

CREATE TABLE IF NOT EXISTS "IdempotencyRecord" (
    idempotency_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    actor_id UUID,
    operation VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    resulting_id UUID,
    response_payload TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_idempotency_actor_op_key UNIQUE (actor_id, operation, idempotency_key)
);

